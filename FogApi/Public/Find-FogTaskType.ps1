function Find-FogTaskType {
    <#
    .SYNOPSIS
    Finds tasktype objects matching a search term.

    .DESCRIPTION
    Matches the term across the tasktype class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogTaskType -stringToSearch 'Example'

    Returns every tasktype matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleTasktype" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchTasktype'
    (GET /tasktype/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog tasktype for $stringToSearch";
        return (Find-FogObject -coreObject tasktype -stringToSearch $stringToSearch).data;
    }

}
