function Find-FogFileDeleteQueue {
    <#
    .SYNOPSIS
    Finds filedeletequeue objects matching a search term.

    .DESCRIPTION
    Matches the term across the filedeletequeue class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogFileDeleteQueue -stringToSearch 'Example'

    Returns every filedeletequeue matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchFiledeletequeue'
    (GET /filedeletequeue/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog filedeletequeue for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject filedeletequeue -stringToSearch $stringToSearch).data -TypeName 'FogApi.Filedeletequeue');
    }

}
