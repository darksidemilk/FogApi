function Find-FogSnapinJob {
    <#
    .SYNOPSIS
    Finds snapinjob objects matching a search term.

    .DESCRIPTION
    Matches the term across the snapinjob class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogSnapinJob -stringToSearch 'Example'

    Returns every snapinjob matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchSnapinjob'
    (GET /snapinjob/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog snapinjob for $stringToSearch";
        return (Find-FogObject -coreObject snapinjob -stringToSearch $stringToSearch).data;
    }

}
