function Find-FogPxeMenuOption {
    <#
    .SYNOPSIS
    Finds pxemenuoptions objects matching a search term.

    .DESCRIPTION
    Matches the term across the pxemenuoptions class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogPxeMenuOption -stringToSearch 'Example'

    Returns every pxemenuoptions matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExamplePxemenuoptions" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchPxemenuoptions'
    (GET /pxemenuoptions/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'ipxe.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog pxemenuoptions for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject pxemenuoptions -stringToSearch $stringToSearch).data -TypeName 'FogApi.Pxemenuoptions');
    }

}
