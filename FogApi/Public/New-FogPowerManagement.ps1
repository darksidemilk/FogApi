function New-FogPowerManagement {
    <#
    .SYNOPSIS
    Creates a powermanagement.

    .DESCRIPTION
    Creates a new powermanagement object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER hostID
    Sets the hostID field (column pmHostID).

    .PARAMETER min
    Sets the min field (column pmMin).

    .PARAMETER hour
    Sets the hour field (column pmHour).

    .PARAMETER dom
    Sets the dom field (column pmDom).

    .PARAMETER month
    Sets the month field (column pmMonth).

    .PARAMETER dow
    Sets the dow field (column pmDow).

    .PARAMETER onDemand
    Sets the onDemand field (column pmOndemand).

    .PARAMETER action
    Sets the action field (column pmAction).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogPowerManagement -hostID 1 -action 'shutdown'

    Creates a powermanagement and returns the created object.

    Expected output:
    { "id": 1, "hostID": 1, "action": "shutdown" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createPowermanagement'
    (POST /powermanagement) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [int]$hostID,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$min,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$hour,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$dom,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$month,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$dow,
        [Parameter()]
        [ValidateSet('0','1')]
        [string]$onDemand,
        [Parameter(Mandatory=$true)]
        [ValidateSet('shutdown','reboot','wol')]
        [string]$action,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('hostID')) { $payload.hostID = $hostID; }
        if ($PSBoundParameters.ContainsKey('min')) { $payload.min = $min; }
        if ($PSBoundParameters.ContainsKey('hour')) { $payload.hour = $hour; }
        if ($PSBoundParameters.ContainsKey('dom')) { $payload.dom = $dom; }
        if ($PSBoundParameters.ContainsKey('month')) { $payload.month = $month; }
        if ($PSBoundParameters.ContainsKey('dow')) { $payload.dow = $dow; }
        if ($PSBoundParameters.ContainsKey('onDemand')) { $payload.onDemand = $onDemand; }
        if ($PSBoundParameters.ContainsKey('action')) { $payload.action = $action; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog powermanagement";
        return New-FogObject -type object -coreObject powermanagement -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
