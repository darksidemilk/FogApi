function Update-FogPowerManagement {
    <#
    .SYNOPSIS
    Updates a powermanagement.

    .DESCRIPTION
    Sends only the fields you name. FOG merges an edit into the existing row, so
    an unbound parameter is left alone rather than blanked -- which is why this
    builds its payload from $PSBoundParameters rather than from every parameter.

    .PARAMETER id
    The id of the powermanagement to update. Accepts an id or an object with an id property, and binds from the pipeline.

    .PARAMETER hostID
    Sets the hostID field (column pmHostID).

    .PARAMETER min
    Sets the min field (column pmMin). At most 50 characters.

    .PARAMETER hour
    Sets the hour field (column pmHour). At most 50 characters.

    .PARAMETER dom
    Sets the dom field (column pmDom). At most 50 characters.

    .PARAMETER month
    Sets the month field (column pmMonth). At most 50 characters.

    .PARAMETER dow
    Sets the dow field (column pmDow). At most 50 characters.

    .PARAMETER onDemand
    Sets the onDemand field (column pmOndemand).

    .PARAMETER action
    Sets the action field (column pmAction).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters.

    .EXAMPLE
    Update-FogPowerManagement -id 1 -min 'Updated'

    Updates the min of powermanagement 1.

    Expected output:
    { "min": "Updated" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'updatePowermanagement'
    (PUT /powermanagement/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.edit' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id,
        [Parameter()]
        [int]$hostID,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$min,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$hour,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$dom,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$month,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$dow,
        [Parameter()]
        [ValidateSet('0','1')]
        [string]$onDemand,
        [Parameter()]
        [ValidateSet('shutdown','reboot','wol')]
        [string]$action,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('hostID')) { $payload.hostID = $hostID; }
        if ($PSBoundParameters.ContainsKey('min')) { $payload.min = $min; }
        if ($PSBoundParameters.ContainsKey('hour')) { $payload.hour = $hour; }
        if ($PSBoundParameters.ContainsKey('dom')) { $payload.dom = $dom; }
        if ($PSBoundParameters.ContainsKey('month')) { $payload.month = $month; }
        if ($PSBoundParameters.ContainsKey('dow')) { $payload.dow = $dow; }
        if ($PSBoundParameters.ContainsKey('onDemand')) { $payload.onDemand = $onDemand; }
        if ($PSBoundParameters.ContainsKey('action')) { $payload.action = $action; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "updating fog powermanagement $objectId";
        return (Add-FogTypeName -InputObject (Update-FogObject -type object -coreObject powermanagement -IDofObject $objectId -jsonData ($payload | ConvertTo-Json -Compress)) -TypeName 'FogApi.Powermanagement');
    }

}
