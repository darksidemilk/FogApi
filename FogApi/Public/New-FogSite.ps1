function New-FogSite {
    <#
    .SYNOPSIS
    Creates a site.

    .DESCRIPTION
    Creates a new site object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER name
    Sets the name field (column siteName).

    .PARAMETER description
    Sets the description field (column siteDesc).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogSite -name 'ExampleSite'

    Creates a site and returns the created object.

    Expected output:
    { "id": 1, "name": "ExampleSite" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createSite'
    (POST /site) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'site.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,255)]
        [string]$name,
        [Parameter()]
        [string]$description,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('description')) { $payload.description = $description; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog site";
        return (Add-FogTypeName -InputObject (New-FogObject -type object -coreObject site -jsonData ($payload | ConvertTo-Json -Compress)) -TypeName 'FogApi.Site');
    }

}
