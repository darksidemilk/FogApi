function Find-FogSnapin {
    <#
    .SYNOPSIS
    Finds snapin objects matching a search term.

    .DESCRIPTION
    Matches the term across the snapin class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogSnapin -stringToSearch 'Example'

    Returns every snapin matching "Example".

    Expected output:
    [ { "id": 5, "name": "office365" }, { "id": 6, "name": "chrome" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchSnapin'
    (GET /snapin/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'snapin.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog snapin for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject snapin -stringToSearch $stringToSearch).data -TypeName 'FogApi.Snapin');
    }

}
