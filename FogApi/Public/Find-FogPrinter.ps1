function Find-FogPrinter {
    <#
    .SYNOPSIS
    Finds printer objects matching a search term.

    .DESCRIPTION
    Matches the term across the printer class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogPrinter -stringToSearch 'Example'

    Returns every printer matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExamplePrinter" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchPrinter'
    (GET /printer/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'printer.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog printer for $stringToSearch";
        return (Find-FogObject -coreObject printer -stringToSearch $stringToSearch).data;
    }

}
