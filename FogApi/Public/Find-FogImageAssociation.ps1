function Find-FogImageAssociation {
    <#
    .SYNOPSIS
    Finds imageassociation objects matching a search term.

    .DESCRIPTION
    Matches the term across the imageassociation class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogImageAssociation -stringToSearch 'Example'

    Returns every imageassociation matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchImageassociation'
    (GET /imageassociation/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'image.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog imageassociation for $stringToSearch";
        return (Find-FogObject -coreObject imageassociation -stringToSearch $stringToSearch).data;
    }

}
