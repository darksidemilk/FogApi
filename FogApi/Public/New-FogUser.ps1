function New-FogUser {
    <#
    .SYNOPSIS
    Creates a user.

    .DESCRIPTION
    Creates a new user object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER name
    Sets the name field (column uName).

    .PARAMETER password
    Sets the password field (column uPass).

    .PARAMETER type
    Sets the type field (column uType).

    .PARAMETER display
    Sets the display field (column uDisplay).

    .PARAMETER api
    Sets the api field (column uAllowAPI).

    .PARAMETER authsource
    Sets the authsource field (column uAuthSource).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogUser -name 'ExampleUser' -password 'example'

    Creates a user and returns the created object.

    Expected output:
    { "id": 1, "name": "ExampleUser", "password": "example" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createUser'
    (POST /user) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'user.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,255)]
        [string]$name,
        [Parameter(Mandatory=$true)]
        [string]$password,
        [Parameter()]
        [int]$type,
        [Parameter()]
        [ValidateLength(0,255)]
        [string]$display,
        [Parameter()]
        [ValidateSet('0','1')]
        [string]$api,
        [Parameter()]
        [ValidateLength(0,32)]
        [string]$authsource,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('password')) { $payload.password = $password; }
        if ($PSBoundParameters.ContainsKey('type')) { $payload.type = $type; }
        if ($PSBoundParameters.ContainsKey('display')) { $payload.display = $display; }
        if ($PSBoundParameters.ContainsKey('api')) { $payload.api = $api; }
        if ($PSBoundParameters.ContainsKey('authsource')) { $payload.authsource = $authsource; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog user";
        return New-FogObject -type object -coreObject user -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
