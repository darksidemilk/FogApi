function Find-FogRoleUserAssociation {
    <#
    .SYNOPSIS
    Finds roleuserassociation objects matching a search term.

    .DESCRIPTION
    Matches the term across the roleuserassociation class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogRoleUserAssociation -stringToSearch 'Example'

    Returns every roleuserassociation matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleRoleuserassociation" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchRoleuserassociation'
    (GET /roleuserassociation/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'role.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog roleuserassociation for $stringToSearch";
        return (Find-FogObject -coreObject roleuserassociation -stringToSearch $stringToSearch).data;
    }

}
