function Remove-FogSnapin {
    <#
    .SYNOPSIS
    Removes a snapin.

    .DESCRIPTION
    Deletes the snapin with the given id. The row is gone; FOG has no undo for this.

    .PARAMETER id
    The id of the snapin to remove. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Remove-FogSnapin -id 1

    Removes snapin 1.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'deleteSnapin'
    (DELETE /snapin/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'snapin.delete' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        Write-Verbose "removing fog snapin $objectId";
        return Remove-FogObject -type object -coreObject snapin -IDofObject $objectId;
    }

}
