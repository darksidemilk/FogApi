function Find-FogNotifyEvent {
    <#
    .SYNOPSIS
    Finds notifyevent objects matching a search term.

    .DESCRIPTION
    Matches the term across the notifyevent class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogNotifyEvent -stringToSearch 'Example'

    Returns every notifyevent matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleNotifyevent" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchNotifyevent'
    (GET /notifyevent/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'settings.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog notifyevent for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject notifyevent -stringToSearch $stringToSearch).data -TypeName 'FogApi.Notifyevent');
    }

}
