function Find-FogMulticastSession {
    <#
    .SYNOPSIS
    Finds multicastsession objects matching a search term.

    .DESCRIPTION
    Matches the term across the multicastsession class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogMulticastSession -stringToSearch 'Example'

    Returns every multicastsession matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleMulticastsession" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchMulticastsession'
    (GET /multicastsession/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog multicastsession for $stringToSearch";
        return (Find-FogObject -coreObject multicastsession -stringToSearch $stringToSearch).data;
    }

}
