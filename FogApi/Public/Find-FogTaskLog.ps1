function Find-FogTaskLog {
    <#
    .SYNOPSIS
    Finds tasklog objects matching a search term.

    .DESCRIPTION
    Matches the term across the tasklog class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogTaskLog -stringToSearch 'Example'

    Returns every tasklog matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchTasklog'
    (GET /tasklog/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog tasklog for $stringToSearch";
        return (Find-FogObject -coreObject tasklog -stringToSearch $stringToSearch).data;
    }

}
