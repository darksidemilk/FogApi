function New-FogPrinterAssociation {
    <#
    .SYNOPSIS
    Creates a printerassociation.

    .DESCRIPTION
    Creates a new printerassociation object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER hostID
    Sets the hostID field (column paHostID).

    .PARAMETER printerID
    Sets the printerID field (column paPrinterID).

    .PARAMETER isDefault
    Sets the isDefault field (column paIsDefault).

    .PARAMETER anon1
    Sets the anon1 field (column paAnon1).

    .PARAMETER anon2
    Sets the anon2 field (column paAnon2).

    .PARAMETER anon3
    Sets the anon3 field (column paAnon3).

    .PARAMETER anon4
    Sets the anon4 field (column paAnon4).

    .PARAMETER anon5
    Sets the anon5 field (column paAnon5).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogPrinterAssociation -hostID 1 -printerID 1

    Creates a printerassociation and returns the created object.

    Expected output:
    { "id": 1, "hostID": 1, "printerID": 1 }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createPrinterassociation'
    (POST /printerassociation) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'printer.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [int]$hostID,
        [Parameter(Mandatory=$true)]
        [int]$printerID,
        [Parameter()]
        [ValidateLength(0,2)]
        [string]$isDefault,
        [Parameter()]
        [ValidateLength(0,2)]
        [string]$anon1,
        [Parameter()]
        [ValidateLength(0,2)]
        [string]$anon2,
        [Parameter()]
        [ValidateLength(0,2)]
        [string]$anon3,
        [Parameter()]
        [ValidateLength(0,2)]
        [string]$anon4,
        [Parameter()]
        [ValidateLength(0,2)]
        [string]$anon5,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('hostID')) { $payload.hostID = $hostID; }
        if ($PSBoundParameters.ContainsKey('printerID')) { $payload.printerID = $printerID; }
        if ($PSBoundParameters.ContainsKey('isDefault')) { $payload.isDefault = $isDefault; }
        if ($PSBoundParameters.ContainsKey('anon1')) { $payload.anon1 = $anon1; }
        if ($PSBoundParameters.ContainsKey('anon2')) { $payload.anon2 = $anon2; }
        if ($PSBoundParameters.ContainsKey('anon3')) { $payload.anon3 = $anon3; }
        if ($PSBoundParameters.ContainsKey('anon4')) { $payload.anon4 = $anon4; }
        if ($PSBoundParameters.ContainsKey('anon5')) { $payload.anon5 = $anon5; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog printerassociation";
        return New-FogObject -type object -coreObject printerassociation -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
