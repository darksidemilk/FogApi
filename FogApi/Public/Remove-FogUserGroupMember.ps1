function Remove-FogUserGroupMember {
    <#
    .SYNOPSIS
    Removes a usergroupmember.

    .DESCRIPTION
    Deletes the usergroupmember with the given id. The row is gone; FOG has no undo for this.

    .PARAMETER id
    The id of the usergroupmember to remove. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Remove-FogUserGroupMember -id 1

    Removes usergroupmember 1.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'deleteUsergroupmember'
    (DELETE /usergroupmember/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'usergroup.delete' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        Write-Verbose "removing fog usergroupmember $objectId";
        return Remove-FogObject -type object -coreObject usergroupmember -IDofObject $objectId;
    }

}
