function Stop-FogMulticastSessionTask {
    <#
    .SYNOPSIS
    Cancels the active task on a multicastsession.

    .DESCRIPTION
    Cancels whatever task is currently queued or running for the multicastsession with the
    given id. Cancelling a task that is not there is not an error.

    .PARAMETER id
    The id of the multicastsession whose task should be cancelled. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Stop-FogMulticastSessionTask -id 1

    Cancels the active task on multicastsession 1.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'cancelMulticastsession'
    (DELETE /multicastsession/{id}/cancel) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.task' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [FogObjectRefTransform()]
        [Object]$id
    )

    process {
        Write-Verbose "cancelling the fog multicastsession task on $id";
        return Remove-FogObject -type objecttasktype -coreTaskObject multicastsession -IDofObject $id;
    }

}
