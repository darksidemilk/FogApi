function Find-FogImagingLog {
    <#
    .SYNOPSIS
    Finds imaginglog objects matching a search term.

    .DESCRIPTION
    Matches the term across the imaginglog class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogImagingLog -stringToSearch 'Example'

    Returns every imaginglog matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchImaginglog'
    (GET /imaginglog/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'report.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog imaginglog for $stringToSearch";
        return (Find-FogObject -coreObject imaginglog -stringToSearch $stringToSearch).data;
    }

}
