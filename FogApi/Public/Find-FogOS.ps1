function Find-FogOS {
    <#
    .SYNOPSIS
    Finds os objects matching a search term.

    .DESCRIPTION
    Matches the term across the os class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogOS -stringToSearch 'Example'

    Returns every os matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleOs" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchOs'
    (GET /os/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'image.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog os for $stringToSearch";
        return (Find-FogObject -coreObject os -stringToSearch $stringToSearch).data;
    }

}
