function Find-FogTaskState {
    <#
    .SYNOPSIS
    Finds taskstate objects matching a search term.

    .DESCRIPTION
    Matches the term across the taskstate class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogTaskState -stringToSearch 'Example'

    Returns every taskstate matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleTaskstate" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchTaskstate'
    (GET /taskstate/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog taskstate for $stringToSearch";
        return (Find-FogObject -coreObject taskstate -stringToSearch $stringToSearch).data;
    }

}
