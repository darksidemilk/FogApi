function Find-FogSetting {
    <#
    .SYNOPSIS
    Finds setting objects matching a search term.

    .DESCRIPTION
    Matches the term across the setting class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogSetting -stringToSearch 'Example'

    Returns every setting matching "Example".

    Expected output:
    [ { "id": 1, "name": "FOG_QUICKREG_PENDING_MAC_FILTER" }, { "id": 2, "name": "FOG_MEMORY_LIMIT" }, { "id": 3, "name": "FOG_WEB_HOST" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchSetting'
    (GET /setting/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'settings.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog setting for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject setting -stringToSearch $stringToSearch).data -TypeName 'FogApi.Setting');
    }

}
