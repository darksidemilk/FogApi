function Find-FogPowerManagement {
    <#
    .SYNOPSIS
    Finds powermanagement objects matching a search term.

    .DESCRIPTION
    Matches the term across the powermanagement class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogPowerManagement -stringToSearch 'Example'

    Returns every powermanagement matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchPowermanagement'
    (GET /powermanagement/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog powermanagement for $stringToSearch";
        return (Find-FogObject -coreObject powermanagement -stringToSearch $stringToSearch).data;
    }

}
