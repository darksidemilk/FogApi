function Remove-FogGroupAssociation {
    <#
    .SYNOPSIS
    Removes a groupassociation.

    .DESCRIPTION
    Deletes the groupassociation with the given id. The row is gone; FOG has no undo for this.

    .PARAMETER id
    The id of the groupassociation to remove. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Remove-FogGroupAssociation -id 1

    Removes groupassociation 1.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'deleteGroupassociation'
    (DELETE /groupassociation/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'group.delete' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        Write-Verbose "removing fog groupassociation $objectId";
        return Remove-FogObject -type object -coreObject groupassociation -IDofObject $objectId;
    }

}
