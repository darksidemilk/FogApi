function Find-FogScheduledTask {
    <#
    .SYNOPSIS
    Finds scheduledtask objects matching a search term.

    .DESCRIPTION
    Matches the term across the scheduledtask class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogScheduledTask -stringToSearch 'Example'

    Returns every scheduledtask matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleScheduledtask" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchScheduledtask'
    (GET /scheduledtask/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog scheduledtask for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject scheduledtask -stringToSearch $stringToSearch).data -TypeName 'FogApi.Scheduledtask');
    }

}
