function Find-FogTask {
    <#
    .SYNOPSIS
    Finds task objects matching a search term.

    .DESCRIPTION
    Matches the term across the task class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogTask -stringToSearch 'Example'

    Returns every task matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleTask" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchTask'
    (GET /task/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog task for $stringToSearch";
        return (Find-FogObject -coreObject task -stringToSearch $stringToSearch).data;
    }

}
