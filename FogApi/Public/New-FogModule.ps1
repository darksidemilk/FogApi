function New-FogModule {
    <#
    .SYNOPSIS
    Creates a module.

    .DESCRIPTION
    Creates a new module object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER name
    Sets the name field (column name).

    .PARAMETER shortName
    Sets the shortName field (column short_name).

    .PARAMETER description
    Sets the description field (column description).

    .PARAMETER isDefault
    Sets the isDefault field (column default).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogModule -name 'ExampleModule' -shortName 'example'

    Creates a module and returns the created object.

    Expected output:
    { "id": 1, "name": "ExampleModule", "shortName": "example" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createModule'
    (POST /module) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'module.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,50)]
        [string]$name,
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,30)]
        [string]$shortName,
        [Parameter()]
        [string]$description,
        [Parameter()]
        [int]$isDefault,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('shortName')) { $payload.shortName = $shortName; }
        if ($PSBoundParameters.ContainsKey('description')) { $payload.description = $description; }
        if ($PSBoundParameters.ContainsKey('isDefault')) { $payload.isDefault = $isDefault; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog module";
        return New-FogObject -type object -coreObject module -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
