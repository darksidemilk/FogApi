function Find-FogHost {
    <#
    .SYNOPSIS
    Finds host objects matching a search term.

    .DESCRIPTION
    Matches the term across the host class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogHost -stringToSearch 'Example'

    Returns every host matching "Example".

    Expected output:
    [ { "id": 42, "name": "MeowMachine" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchHost'
    (GET /host/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog host for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject host -stringToSearch $stringToSearch).data -TypeName 'FogApi.Host');
    }

}
