function Update-FogUser {
    <#
    .SYNOPSIS
    Updates a user.

    .DESCRIPTION
    Sends only the fields you name. FOG merges an edit into the existing row, so
    an unbound parameter is left alone rather than blanked -- which is why this
    builds its payload from $PSBoundParameters rather than from every parameter.

    .PARAMETER id
    The id of the user to update. Accepts an id or an object with an id property, and binds from the pipeline.

    .PARAMETER name
    Sets the name field (column uName). At most 255 characters.

    .PARAMETER password
    Sets the password field (column uPass).

    .PARAMETER type
    Sets the type field (column uType).

    .PARAMETER display
    Sets the display field (column uDisplay). At most 255 characters.

    .PARAMETER api
    Sets the api field (column uAllowAPI).

    .PARAMETER authsource
    Sets the authsource field (column uAuthSource). At most 32 characters.

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters.

    .EXAMPLE
    Update-FogUser -id 1 -name 'Updated'

    Updates the name of user 1.

    Expected output:
    { "name": "Updated" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'updateUser'
    (PUT /user/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'user.edit' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id,
        [Parameter()]
        [ValidateLength(0,255)]
        [string]$name,
        [Parameter()]
        [string]$password,
        [Parameter()]
        [int]$type,
        [Parameter()]
        [ValidateLength(0,255)]
        [string]$display,
        [Parameter()]
        [ValidateSet('0','1')]
        [string]$api,
        [Parameter()]
        [ValidateLength(0,32)]
        [string]$authsource,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('password')) { $payload.password = $password; }
        if ($PSBoundParameters.ContainsKey('type')) { $payload.type = $type; }
        if ($PSBoundParameters.ContainsKey('display')) { $payload.display = $display; }
        if ($PSBoundParameters.ContainsKey('api')) { $payload.api = $api; }
        if ($PSBoundParameters.ContainsKey('authsource')) { $payload.authsource = $authsource; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "updating fog user $objectId";
        return (Add-FogTypeName -InputObject (Update-FogObject -type object -coreObject user -IDofObject $objectId -jsonData ($payload | ConvertTo-Json -Compress)) -TypeName 'FogApi.User');
    }

}
