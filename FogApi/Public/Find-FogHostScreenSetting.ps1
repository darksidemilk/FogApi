function Find-FogHostScreenSetting {
    <#
    .SYNOPSIS
    Finds hostscreensetting objects matching a search term.

    .DESCRIPTION
    Matches the term across the hostscreensetting class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogHostScreenSetting -stringToSearch 'Example'

    Returns every hostscreensetting matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchHostscreensetting'
    (GET /hostscreensetting/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog hostscreensetting for $stringToSearch";
        return (Find-FogObject -coreObject hostscreensetting -stringToSearch $stringToSearch).data;
    }

}
