function Find-FogNodeFailure {
    <#
    .SYNOPSIS
    Finds nodefailure objects matching a search term.

    .DESCRIPTION
    Matches the term across the nodefailure class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogNodeFailure -stringToSearch 'Example'

    Returns every nodefailure matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchNodefailure'
    (GET /nodefailure/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog nodefailure for $stringToSearch";
        return (Find-FogObject -coreObject nodefailure -stringToSearch $stringToSearch).data;
    }

}
