function Get-FogPrinter {
    <#
    .SYNOPSIS
    Gets one printer by id.

    .DESCRIPTION
    Returns a single printer object. Fields the list route withholds are returned
    here, which is the reason to fetch by id rather than filter a list.

    .PARAMETER id
    The id of the printer to get. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Get-FogPrinter -id 1

    Returns the printer with id 1.

    Expected output:
    { "id": 1, "name": "ExamplePrinter" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'indivPrinter'
    (GET /printer/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'printer.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id
    )

    process {
        # An id, or an object carrying one. Every generated cmdlet accepts both,
        # so a result from one can be piped straight into another.
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        Write-Verbose "getting fog printer $objectId";
        # No .data here. Get-FogObject only runs its result through
        # Add-FogResultData when no id was given, because a fetch by id returns the
        # bare object rather than a list envelope. Taking .data returns $null.
        return Get-FogObject -type object -coreObject printer -IDofObject $objectId;
    }

}
