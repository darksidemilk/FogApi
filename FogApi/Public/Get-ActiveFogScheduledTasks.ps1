function Get-ActiveFogScheduledTasks {
    <#
    .SYNOPSIS
    Gets the currently active scheduledtask entries.

    .DESCRIPTION
    Returns what FOG considers in flight right now for scheduledtask -- the /current
    route, which is a filtered view rather than a page of the full list, so it
    takes no paging parameters.

    .EXAMPLE
    Get-ActiveFogScheduledTasks

    Lists the active scheduledtask entries.

    Expected output:
    { "id": 1, "name": "example" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'activeScheduledtask'
    (GET /scheduledtask/current) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'task.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
    )

    process {
        Write-Verbose "getting the active fog scheduledtask entries";
        return (Add-FogTypeName -InputObject (Get-FogObject -type objectactivetasktype -coreActiveTaskObject scheduledtask) -TypeName 'FogApi.Scheduledtask');
    }

}
