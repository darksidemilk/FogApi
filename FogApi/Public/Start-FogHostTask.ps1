function Start-FogHostTask {
    <#
    .SYNOPSIS
    Queues a task against a host.

    .DESCRIPTION
    Posts a task request to /host/{id}/task, which is how FOG queues imaging, snapin,
    password-reset and wake-on-lan work. Wake-on-lan is this route with wol
    set, not a route of its own.

    The body is the same on FOG 1.5 and 1.6: both hand it to
    createImagePackage() and read the same eight fields, so there is no
    version branch here.

    .PARAMETER id
    The id of the host to task. Accepts an id or an object with an id property, and binds from the pipeline.

    .PARAMETER TaskRequest
    The task body, from New-FogTaskRequest or as a hashtable. Only the fields it sets are sent.

    .EXAMPLE
    Start-FogHostTask -id 1 -TaskRequest @{ taskTypeID = 1 }

    Queues a deploy task against host 1.

    Expected output:
    ""

    .EXAMPLE
    Get-FogHost -id 1 | Start-FogHostTask -TaskRequest (New-FogTaskRequest -taskTypeID 14 -wol $true)

    Wakes host 1, passing the object straight down the pipeline.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'taskHost'
    (POST /host/{id}/task) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.task' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [FogObjectRefTransform()]
        [Object]$id,
        [Parameter(Position=1)]
        [FogTaskRequest]$TaskRequest
    )

    process {
        $request = if ($PSBoundParameters.ContainsKey('TaskRequest')) { $TaskRequest } else { [FogTaskRequest]::new() };
        Write-Verbose "queuing a fog host task on $id";
        return New-FogObject -type objecttasktype -coreTaskObject host -IDofObject $id -jsonData $request;
    }

}
