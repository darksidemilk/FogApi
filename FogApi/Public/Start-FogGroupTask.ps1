function Start-FogGroupTask {
    <#
    .SYNOPSIS
    Queues a task against a group.

    .DESCRIPTION
    Posts a task request to /group/{id}/task, which is how FOG queues imaging, snapin,
    password-reset and wake-on-lan work. Wake-on-lan is this route with wol
    set, not a route of its own.

    The body is the same on FOG 1.5 and 1.6: both hand it to
    createImagePackage() and read the same eight fields, so there is no
    version branch here.

    .PARAMETER id
    The id of the group to task. Accepts an id or an object with an id property, and binds from the pipeline.

    .PARAMETER TaskRequest
    The task body, from New-FogTaskRequest or as a hashtable. Only the fields it sets are sent.

    .EXAMPLE
    Start-FogGroupTask -id 1 -TaskRequest @{ taskTypeID = 1 }

    Queues a deploy task against group 1.

    Expected output:
    ""

    .EXAMPLE
    Get-FogObject -type object -coreObject group -IDofObject 1 | Start-FogGroupTask -TaskRequest (New-FogTaskRequest -taskTypeID 14 -wol $true)

    Wakes group 1, passing the object straight down the pipeline.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'taskGroup'
    (POST /group/{id}/task) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'group.task' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [FogObjectRefTransform()]
        [Object]$id,
        [Parameter(Position=1)]
        [FogTaskRequest]$TaskRequest
    )

    process {
        $request = if ($PSBoundParameters.ContainsKey('TaskRequest')) { $TaskRequest } else { [FogTaskRequest]::new() };
        Write-Verbose "queuing a fog group task on $id";
        return New-FogObject -type objecttasktype -coreTaskObject group -IDofObject $id -jsonData $request;
    }

}
