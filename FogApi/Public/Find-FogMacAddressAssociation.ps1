function Find-FogMacAddressAssociation {
    <#
    .SYNOPSIS
    Finds macaddressassociation objects matching a search term.

    .DESCRIPTION
    Matches the term across the macaddressassociation class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogMacAddressAssociation -stringToSearch 'Example'

    Returns every macaddressassociation matching "Example".

    Expected output:
    [ { "id": 10 }, { "id": 11 }, { "id": 12 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchMacaddressassociation'
    (GET /macaddressassociation/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog macaddressassociation for $stringToSearch";
        return (Find-FogObject -coreObject macaddressassociation -stringToSearch $stringToSearch).data;
    }

}
