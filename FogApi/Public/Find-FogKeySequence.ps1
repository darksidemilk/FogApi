function Find-FogKeySequence {
    <#
    .SYNOPSIS
    Finds keysequence objects matching a search term.

    .DESCRIPTION
    Matches the term across the keysequence class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogKeySequence -stringToSearch 'Example'

    Returns every keysequence matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleKeysequence" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchKeysequence'
    (GET /keysequence/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'ipxe.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog keysequence for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject keysequence -stringToSearch $stringToSearch).data -TypeName 'FogApi.Keysequence');
    }

}
