function Find-FogIpxe {
    <#
    .SYNOPSIS
    Finds ipxe objects matching a search term.

    .DESCRIPTION
    Matches the term across the ipxe class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogIpxe -stringToSearch 'Example'

    Returns every ipxe matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchIpxe'
    (GET /ipxe/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'ipxe.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog ipxe for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject ipxe -stringToSearch $stringToSearch).data -TypeName 'FogApi.Ipxe');
    }

}
