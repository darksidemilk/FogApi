function Find-FogHistory {
    <#
    .SYNOPSIS
    Finds history objects matching a search term.

    .DESCRIPTION
    Matches the term across the history class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogHistory -stringToSearch 'Example'

    Returns every history matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchHistory'
    (GET /history/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'report.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog history for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject history -stringToSearch $stringToSearch).data -TypeName 'FogApi.History');
    }

}
