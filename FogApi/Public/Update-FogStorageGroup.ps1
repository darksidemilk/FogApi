function Update-FogStorageGroup {
    <#
    .SYNOPSIS
    Updates a storagegroup.

    .DESCRIPTION
    Sends only the fields you name. FOG merges an edit into the existing row, so
    an unbound parameter is left alone rather than blanked -- which is why this
    builds its payload from $PSBoundParameters rather than from every parameter.

    .PARAMETER id
    The id of the storagegroup to update. Accepts an id or an object with an id property, and binds from the pipeline.

    .PARAMETER name
    Sets the name field (column ngName). At most 250 characters.

    .PARAMETER description
    Sets the description field (column ngDesc).

    .PARAMETER trustedcidrs
    Sets the trustedcidrs field (column ngTrustedCIDRs). At most 2048 characters.

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters.

    .EXAMPLE
    Update-FogStorageGroup -id 1 -name 'Updated'

    Updates the name of storagegroup 1.

    Expected output:
    { "name": "Updated" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'updateStoragegroup'
    (PUT /storagegroup/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'storagegroup.edit' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id,
        [Parameter()]
        [ValidateLength(0,250)]
        [string]$name,
        [Parameter()]
        [string]$description,
        [Parameter()]
        [ValidateLength(0,2048)]
        [string]$trustedcidrs,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('description')) { $payload.description = $description; }
        if ($PSBoundParameters.ContainsKey('trustedcidrs')) { $payload.trustedcidrs = $trustedcidrs; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "updating fog storagegroup $objectId";
        return Update-FogObject -type object -coreObject storagegroup -IDofObject $objectId -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
