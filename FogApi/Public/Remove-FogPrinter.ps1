function Remove-FogPrinter {
    <#
    .SYNOPSIS
    Removes a printer.

    .DESCRIPTION
    Deletes the printer with the given id. The row is gone; FOG has no undo for this.

    .PARAMETER id
    The id of the printer to remove. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Remove-FogPrinter -id 1

    Removes printer 1.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'deletePrinter'
    (DELETE /printer/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'printer.delete' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        Write-Verbose "removing fog printer $objectId";
        return Remove-FogObject -type object -coreObject printer -IDofObject $objectId;
    }

}
