function Update-FogModule {
    <#
    .SYNOPSIS
    Updates a module.

    .DESCRIPTION
    Sends only the fields you name. FOG merges an edit into the existing row, so
    an unbound parameter is left alone rather than blanked -- which is why this
    builds its payload from $PSBoundParameters rather than from every parameter.

    .PARAMETER id
    The id of the module to update. Accepts an id or an object with an id property, and binds from the pipeline.

    .PARAMETER name
    Sets the name field (column name). At most 50 characters.

    .PARAMETER shortName
    Sets the shortName field (column short_name). At most 30 characters.

    .PARAMETER description
    Sets the description field (column description).

    .PARAMETER isDefault
    Sets the isDefault field (column default).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters.

    .EXAMPLE
    Update-FogModule -id 1 -name 'Updated'

    Updates the name of module 1.

    Expected output:
    { "name": "Updated" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'updateModule'
    (PUT /module/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'module.edit' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id,
        [Parameter()]
        [ValidateLength(0,50)]
        [string]$name,
        [Parameter()]
        [ValidateLength(0,30)]
        [string]$shortName,
        [Parameter()]
        [string]$description,
        [Parameter()]
        [int]$isDefault,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('shortName')) { $payload.shortName = $shortName; }
        if ($PSBoundParameters.ContainsKey('description')) { $payload.description = $description; }
        if ($PSBoundParameters.ContainsKey('isDefault')) { $payload.isDefault = $isDefault; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "updating fog module $objectId";
        return (Add-FogTypeName -InputObject (Update-FogObject -type object -coreObject module -IDofObject $objectId -jsonData ($payload | ConvertTo-Json -Compress)) -TypeName 'FogApi.Module');
    }

}
