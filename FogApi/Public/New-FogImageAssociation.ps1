function New-FogImageAssociation {
    <#
    .SYNOPSIS
    Creates a imageassociation.

    .DESCRIPTION
    Creates a new imageassociation object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER imageID
    Sets the imageID field (column igaImageID).

    .PARAMETER storagegroupID
    Sets the storagegroupID field (column igaStorageGroupID).

    .PARAMETER primary
    Sets the primary field (column igaPrimary).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogImageAssociation -imageID 1 -storagegroupID 1

    Creates a imageassociation and returns the created object.

    Expected output:
    { "id": 1, "imageID": 1, "storagegroupID": 1 }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createImageassociation'
    (POST /imageassociation) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'image.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [int]$imageID,
        [Parameter(Mandatory=$true)]
        [int]$storagegroupID,
        [Parameter()]
        [ValidateSet('0','1')]
        [string]$primary,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('imageID')) { $payload.imageID = $imageID; }
        if ($PSBoundParameters.ContainsKey('storagegroupID')) { $payload.storagegroupID = $storagegroupID; }
        if ($PSBoundParameters.ContainsKey('primary')) { $payload.primary = $primary; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog imageassociation";
        return (Add-FogTypeName -InputObject (New-FogObject -type object -coreObject imageassociation -jsonData ($payload | ConvertTo-Json -Compress)) -TypeName 'FogApi.Imageassociation');
    }

}
