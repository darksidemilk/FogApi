function Remove-FogGroup {
    <#
    .SYNOPSIS
    Removes a group.

    .DESCRIPTION
    Deletes the group with the given id. The row is gone; FOG has no undo for this.

    .PARAMETER id
    The id of the group to remove. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Remove-FogGroup -id 1

    Removes group 1.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'deleteGroup'
    (DELETE /group/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'group.delete' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        Write-Verbose "removing fog group $objectId";
        return Remove-FogObject -type object -coreObject group -IDofObject $objectId;
    }

}
