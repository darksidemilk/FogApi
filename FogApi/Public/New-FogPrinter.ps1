function New-FogPrinter {
    <#
    .SYNOPSIS
    Creates a printer.

    .DESCRIPTION
    Creates a new printer object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER name
    Sets the name field (column pAlias).

    .PARAMETER description
    Sets the description field (column pDesc).

    .PARAMETER port
    Sets the port field (column pPort).

    .PARAMETER file
    Sets the file field (column pDefFile).

    .PARAMETER model
    Sets the model field (column pModel).

    .PARAMETER config
    Sets the config field (column pConfig).

    .PARAMETER configFile
    Sets the configFile field (column pConfigFile).

    .PARAMETER ip
    Sets the ip field (column pIP).

    .PARAMETER pAnon2
    Sets the pAnon2 field (column pAnon2).

    .PARAMETER pAnon3
    Sets the pAnon3 field (column pAnon3).

    .PARAMETER pAnon4
    Sets the pAnon4 field (column pAnon4).

    .PARAMETER pAnon5
    Sets the pAnon5 field (column pAnon5).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogPrinter -name 'ExamplePrinter'

    Creates a printer and returns the created object.

    Expected output:
    { "id": 1, "name": "ExamplePrinter" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createPrinter'
    (POST /printer) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'printer.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,250)]
        [string]$name,
        [Parameter()]
        [string]$description,
        [Parameter()]
        [string]$port,
        [Parameter()]
        [string]$file,
        [Parameter()]
        [ValidateLength(0,250)]
        [string]$model,
        [Parameter()]
        [ValidateLength(0,10)]
        [string]$config,
        [Parameter()]
        [ValidateLength(0,255)]
        [string]$configFile,
        [Parameter()]
        [ValidateLength(0,255)]
        [string]$ip,
        [Parameter()]
        [ValidateLength(0,10)]
        [string]$pAnon2,
        [Parameter()]
        [ValidateLength(0,10)]
        [string]$pAnon3,
        [Parameter()]
        [ValidateLength(0,10)]
        [string]$pAnon4,
        [Parameter()]
        [ValidateLength(0,10)]
        [string]$pAnon5,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('description')) { $payload.description = $description; }
        if ($PSBoundParameters.ContainsKey('port')) { $payload.port = $port; }
        if ($PSBoundParameters.ContainsKey('file')) { $payload.file = $file; }
        if ($PSBoundParameters.ContainsKey('model')) { $payload.model = $model; }
        if ($PSBoundParameters.ContainsKey('config')) { $payload.config = $config; }
        if ($PSBoundParameters.ContainsKey('configFile')) { $payload.configFile = $configFile; }
        if ($PSBoundParameters.ContainsKey('ip')) { $payload.ip = $ip; }
        if ($PSBoundParameters.ContainsKey('pAnon2')) { $payload.pAnon2 = $pAnon2; }
        if ($PSBoundParameters.ContainsKey('pAnon3')) { $payload.pAnon3 = $pAnon3; }
        if ($PSBoundParameters.ContainsKey('pAnon4')) { $payload.pAnon4 = $pAnon4; }
        if ($PSBoundParameters.ContainsKey('pAnon5')) { $payload.pAnon5 = $pAnon5; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog printer";
        return New-FogObject -type object -coreObject printer -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
