function Find-FogHookEvent {
    <#
    .SYNOPSIS
    Finds hookevent objects matching a search term.

    .DESCRIPTION
    Matches the term across the hookevent class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogHookEvent -stringToSearch 'Example'

    Returns every hookevent matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleHookevent" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchHookevent'
    (GET /hookevent/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'settings.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog hookevent for $stringToSearch";
        return (Find-FogObject -coreObject hookevent -stringToSearch $stringToSearch).data;
    }

}
