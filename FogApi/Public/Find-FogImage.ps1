function Find-FogImage {
    <#
    .SYNOPSIS
    Finds image objects matching a search term.

    .DESCRIPTION
    Matches the term across the image class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogImage -stringToSearch 'Example'

    Returns every image matching "Example".

    Expected output:
    [ { "id": 3, "name": "Windows 10" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchImage'
    (GET /image/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'image.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog image for $stringToSearch";
        return (Find-FogObject -coreObject image -stringToSearch $stringToSearch).data;
    }

}
