function Find-FogInventory {
    <#
    .SYNOPSIS
    Finds inventory objects matching a search term.

    .DESCRIPTION
    Matches the term across the inventory class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogInventory -stringToSearch 'Example'

    Returns every inventory matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchInventory'
    (GET /inventory/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'host.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog inventory for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject inventory -stringToSearch $stringToSearch).data -TypeName 'FogApi.Inventory');
    }

}
