function Find-FogGroupAssociation {
    <#
    .SYNOPSIS
    Finds groupassociation objects matching a search term.

    .DESCRIPTION
    Matches the term across the groupassociation class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogGroupAssociation -stringToSearch 'Example'

    Returns every groupassociation matching "Example".

    Expected output:
    [ { "id": 9 }, { "id": 10 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchGroupassociation'
    (GET /groupassociation/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'group.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog groupassociation for $stringToSearch";
        return (Find-FogObject -coreObject groupassociation -stringToSearch $stringToSearch).data;
    }

}
