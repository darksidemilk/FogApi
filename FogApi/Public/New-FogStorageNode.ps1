        if ($PSBoundParameters.ContainsKey('isGraphEnabled')) { $payload.isGraphEnabled = $isGraphEnabled; }
        if ($PSBoundParameters.ContainsKey('path')) { $payload.path = $path; }
        if ($PSBoundParameters.ContainsKey('ftppath')) { $payload.ftppath = $ftppath; }
        if ($PSBoundParameters.ContainsKey('bitrate')) { $payload.bitrate = $bitrate; }
        if ($PSBoundParameters.ContainsKey('helloInterval')) { $payload.helloInterval = $helloInterval; }
        if ($PSBoundParameters.ContainsKey('snapinpath')) { $payload.snapinpath = $snapinpath; }
        if ($PSBoundParameters.ContainsKey('sslpath')) { $payload.sslpath = $sslpath; }
        if ($PSBoundParameters.ContainsKey('ip')) { $payload.ip = $ip; }
        if ($PSBoundParameters.ContainsKey('maxClients')) { $payload.maxClients = $maxClients; }
        if ($PSBoundParameters.ContainsKey('user')) { $payload.user = $user; }
        if ($PSBoundParameters.ContainsKey('pass')) { $payload.pass = $pass; }
