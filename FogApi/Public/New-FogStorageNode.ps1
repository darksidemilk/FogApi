        [Parameter()]
        [ValidateSet('0','1')]
        [string]$isGraphEnabled,
        [Parameter(Mandatory=$true)]
        [string]$path,
        [Parameter(Mandatory=$true)]
        [string]$ftppath,
        [Parameter()]
        [ValidateLength(0,25)]
        [string]$bitrate,
        [Parameter()]
        [ValidateLength(0,8)]
        [string]$helloInterval,
        [Parameter()]
        [string]$snapinpath,
        [Parameter()]
        [string]$sslpath,
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,250)]
        [string]$ip,
        [Parameter()]
        [int]$maxClients,
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,250)]
        [string]$user,
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,250)]
        [string]$pass,
        [Parameter()]
        [ValidateLength(0,250)]
        [string]$key,
        [Parameter()]
        [ValidateLength(0,25)]
