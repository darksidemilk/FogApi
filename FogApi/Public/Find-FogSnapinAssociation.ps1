function Find-FogSnapinAssociation {
    <#
    .SYNOPSIS
    Finds snapinassociation objects matching a search term.

    .DESCRIPTION
    Matches the term across the snapinassociation class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogSnapinAssociation -stringToSearch 'Example'

    Returns every snapinassociation matching "Example".

    Expected output:
    [ { "id": 20 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchSnapinassociation'
    (GET /snapinassociation/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'snapin.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog snapinassociation for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject snapinassociation -stringToSearch $stringToSearch).data -TypeName 'FogApi.Snapinassociation');
    }

}
