function Find-FogImagePartitionType {
    <#
    .SYNOPSIS
    Finds imagepartitiontype objects matching a search term.

    .DESCRIPTION
    Matches the term across the imagepartitiontype class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogImagePartitionType -stringToSearch 'Example'

    Returns every imagepartitiontype matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleImagepartitiontype" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchImagepartitiontype'
    (GET /imagepartitiontype/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'image.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog imagepartitiontype for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject imagepartitiontype -stringToSearch $stringToSearch).data -TypeName 'FogApi.Imagepartitiontype');
    }

}
