function New-FogStorageGroup {
    <#
    .SYNOPSIS
    Creates a storagegroup.

    .DESCRIPTION
    Creates a new storagegroup object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER name
    Sets the name field (column ngName).

    .PARAMETER description
    Sets the description field (column ngDesc).

    .PARAMETER trustedcidrs
    Sets the trustedcidrs field (column ngTrustedCIDRs).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogStorageGroup -name 'ExampleStoragegroup'

    Creates a storagegroup and returns the created object.

    Expected output:
    { "id": 1, "name": "ExampleStoragegroup" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createStoragegroup'
    (POST /storagegroup) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'storagegroup.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,250)]
        [string]$name,
        [Parameter()]
        [string]$description,
        [Parameter()]
        [ValidateLength(0,2048)]
        [string]$trustedcidrs,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('description')) { $payload.description = $description; }
        if ($PSBoundParameters.ContainsKey('trustedcidrs')) { $payload.trustedcidrs = $trustedcidrs; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog storagegroup";
        return New-FogObject -type object -coreObject storagegroup -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
