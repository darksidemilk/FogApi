function New-FogModuleAssociation {
    <#
    .SYNOPSIS
    Creates a moduleassociation.

    .DESCRIPTION
    Creates a new moduleassociation object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER hostID
    Sets the hostID field (column msHostID).

    .PARAMETER moduleID
    Sets the moduleID field (column msModuleID).

    .PARAMETER state
    Sets the state field (column msState).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogModuleAssociation -hostID 1 -moduleID 1

    Creates a moduleassociation and returns the created object.

    Expected output:
    { "id": 1, "hostID": 1, "moduleID": 1 }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createModuleassociation'
    (POST /moduleassociation) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'module.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [int]$hostID,
        [Parameter(Mandatory=$true)]
        [int]$moduleID,
        [Parameter()]
        [ValidateLength(0,1)]
        [string]$state,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('hostID')) { $payload.hostID = $hostID; }
        if ($PSBoundParameters.ContainsKey('moduleID')) { $payload.moduleID = $moduleID; }
        if ($PSBoundParameters.ContainsKey('state')) { $payload.state = $state; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog moduleassociation";
        return New-FogObject -type object -coreObject moduleassociation -jsonData ($payload | ConvertTo-Json -Compress);
    }

}
