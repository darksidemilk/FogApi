function Find-FogGroup {
    <#
    .SYNOPSIS
    Finds group objects matching a search term.

    .DESCRIPTION
    Matches the term across the group class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogGroup -stringToSearch 'Example'

    Returns every group matching "Example".

    Expected output:
    [ { "id": 7, "name": "TestGroup" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchGroup'
    (GET /group/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'group.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog group for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject group -stringToSearch $stringToSearch).data -TypeName 'FogApi.Group');
    }

}
