function Get-FogPrinters {
    <#
    .SYNOPSIS
    Gets every printer on the fog server.

    .DESCRIPTION
    Returns all printer objects. On FOG 1.6 the list is paged automatically and
    every page is followed, so the result is complete rather than capped at the
    server's row limit (10000 rows). Filter the result with Where-Object.

    .PARAMETER First
    Return at most this many objects.

    .PARAMETER Skip
    Skip this many objects before returning any.

    .PARAMETER PageSize
    Rows to request per page. Ignored on FOG 1.5, which does not page.

    .PARAMETER NoAutoPage
    Return only the first page instead of following nextUrl.

    .EXAMPLE
    Get-FogPrinters

    Returns an array of every printer.

    Expected output:
    [ { "id": 1, "name": "ExamplePrinter" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'listPrinter'
    (GET /printer) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'printer.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter()]
        [int]$First,
        [Parameter()]
        [int]$Skip,
        [Parameter()]
        [int]$PageSize = 1000,
        [Parameter()]
        [switch]$NoAutoPage
    )

    process {
        Write-Verbose "getting all fog printer objects";
        $splat = @{ type = 'object'; coreObject = 'printer' };
        foreach ($p in @('First','Skip','PageSize','NoAutoPage')) {
            if ($PSBoundParameters.ContainsKey($p)) { $splat[$p] = $PSBoundParameters[$p]; }
        }
        return (Get-FogObject @splat).data;
    }

}
