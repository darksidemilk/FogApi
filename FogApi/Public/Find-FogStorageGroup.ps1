function Find-FogStorageGroup {
    <#
    .SYNOPSIS
    Finds storagegroup objects matching a search term.

    .DESCRIPTION
    Matches the term across the storagegroup class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogStorageGroup -stringToSearch 'Example'

    Returns every storagegroup matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleStoragegroup" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchStoragegroup'
    (GET /storagegroup/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'storagegroup.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog storagegroup for $stringToSearch";
        return (Find-FogObject -coreObject storagegroup -stringToSearch $stringToSearch).data;
    }

}
