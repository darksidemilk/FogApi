function Remove-FogRoleUserAssociation {
    <#
    .SYNOPSIS
    Removes a roleuserassociation.

    .DESCRIPTION
    Deletes the roleuserassociation with the given id. The row is gone; FOG has no undo for this.

    .PARAMETER id
    The id of the roleuserassociation to remove. Accepts an id or an object with an id property, and binds from the pipeline.

    .EXAMPLE
    Remove-FogRoleUserAssociation -id 1

    Removes roleuserassociation 1.

    Expected output:
    ""

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'deleteRoleuserassociation'
    (DELETE /roleuserassociation/{id}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'role.delete' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0,ValueFromPipeline=$true,ValueFromPipelineByPropertyName=$true)]
        [Alias('IDofObject')]
        [Object]$id
    )

    process {
        $objectId = if ($id -is [System.Management.Automation.PSObject] -and $id.PSObject.Properties.Name -contains 'id') { $id.id } else { $id };
        Write-Verbose "removing fog roleuserassociation $objectId";
        return Remove-FogObject -type object -coreObject roleuserassociation -IDofObject $objectId;
    }

}
