function Find-FogUserTracking {
    <#
    .SYNOPSIS
    Finds usertracking objects matching a search term.

    .DESCRIPTION
    Matches the term across the usertracking class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogUserTracking -stringToSearch 'Example'

    Returns every usertracking matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchUsertracking'
    (GET /usertracking/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'usertracking.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog usertracking for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject usertracking -stringToSearch $stringToSearch).data -TypeName 'FogApi.Usertracking');
    }

}
