function Find-FogStorageNode {
    <#
    .SYNOPSIS
    Finds storagenode objects matching a search term.

    .DESCRIPTION
    Matches the term across the storagenode class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogStorageNode -stringToSearch 'Example'

    Returns every storagenode matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleStoragenode" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchStoragenode'
    (GET /storagenode/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'storagenode.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog storagenode for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject storagenode -stringToSearch $stringToSearch).data -TypeName 'FogApi.Storagenode');
    }

}
