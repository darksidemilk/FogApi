function Find-FogPrinterAssociation {
    <#
    .SYNOPSIS
    Finds printerassociation objects matching a search term.

    .DESCRIPTION
    Matches the term across the printerassociation class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogPrinterAssociation -stringToSearch 'Example'

    Returns every printerassociation matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchPrinterassociation'
    (GET /printerassociation/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'printer.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog printerassociation for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject printerassociation -stringToSearch $stringToSearch).data -TypeName 'FogApi.Printerassociation');
    }

}
