function Find-FogOui {
    <#
    .SYNOPSIS
    Finds oui objects matching a search term.

    .DESCRIPTION
    Matches the term across the oui class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogOui -stringToSearch 'Example'

    Returns every oui matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleOui" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchOui'
    (GET /oui/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'settings.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog oui for $stringToSearch";
        return (Find-FogObject -coreObject oui -stringToSearch $stringToSearch).data;
    }

}
