function Find-FogUserGroupMember {
    <#
    .SYNOPSIS
    Finds usergroupmember objects matching a search term.

    .DESCRIPTION
    Matches the term across the usergroupmember class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogUserGroupMember -stringToSearch 'Example'

    Returns every usergroupmember matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleUsergroupmember" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchUsergroupmember'
    (GET /usergroupmember/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'usergroup.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog usergroupmember for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject usergroupmember -stringToSearch $stringToSearch).data -TypeName 'FogApi.Usergroupmember');
    }

}
