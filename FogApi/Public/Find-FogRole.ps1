function Find-FogRole {
    <#
    .SYNOPSIS
    Finds role objects matching a search term.

    .DESCRIPTION
    Matches the term across the role class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogRole -stringToSearch 'Example'

    Returns every role matching "Example".

    Expected output:
    [ { "id": 1, "name": "ExampleRole" } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchRole'
    (GET /role/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'role.view' permission.
    FOG 1.6 only; FOG 1.5 does not serve this operation.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog role for $stringToSearch";
        return (Find-FogObject -coreObject role -stringToSearch $stringToSearch).data;
    }

}
