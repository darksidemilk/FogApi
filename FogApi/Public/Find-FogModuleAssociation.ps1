function Find-FogModuleAssociation {
    <#
    .SYNOPSIS
    Finds moduleassociation objects matching a search term.

    .DESCRIPTION
    Matches the term across the moduleassociation class fields and returns the same envelope
    a list does.

    .PARAMETER stringToSearch
    Text to match across the class fields.

    .EXAMPLE
    Find-FogModuleAssociation -stringToSearch 'Example'

    Returns every moduleassociation matching "Example".

    Expected output:
    [ { "id": 1 } ]

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'searchModuleassociation'
    (GET /moduleassociation/search/{item}) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'module.view' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true,Position=0)]
        [string]$stringToSearch
    )

    process {
        Write-Verbose "searching fog moduleassociation for $stringToSearch";
        return (Add-FogTypeName -InputObject (Find-FogObject -coreObject moduleassociation -stringToSearch $stringToSearch).data -TypeName 'FogApi.Moduleassociation');
    }

}
