function New-FogSetting {
    <#
    .SYNOPSIS
    Creates a setting.

    .DESCRIPTION
    Creates a new setting object. Every writable field of the class is a named
    parameter, with the length and value constraints the server itself declares.
    Use -settings for a field a newer server has added that this module does not
    yet know about.

    .PARAMETER name
    Sets the name field (column settingKey).

    .PARAMETER description
    Sets the description field (column settingDesc).

    .PARAMETER value
    Sets the value field (column settingValue).

    .PARAMETER category
    Sets the category field (column settingCategory).

    .PARAMETER settings
    A hashtable of raw field values, merged over the named parameters. An escape hatch for fields not yet modelled.

    .EXAMPLE
    New-FogSetting -name 'ExampleSetting'

    Creates a setting and returns the created object.

    Expected output:
    { "id": 1, "name": "ExampleSetting" }

    .NOTES
    Generated by spec/tools/New-FogApiFunctionFile.ps1 from operation 'createSetting'
    (POST /setting) in spec/fog-api-spec.json. Edit the spec, not this file.
    Requires the 'settings.create' permission.
    #>

    [CmdletBinding()]
    param (
        [Parameter(Mandatory=$true)]
        [ValidateLength(0,255)]
        [Alias('settingName')]
        [string]$name,
        [Parameter()]
        [string]$description,
        [Parameter()]
        [string]$value,
        [Parameter()]
        [string]$category,
        [Parameter()]
        [hashtable]$settings
    )

    process {
        $payload = @{};
        if ($PSBoundParameters.ContainsKey('name')) { $payload.name = $name; }
        if ($PSBoundParameters.ContainsKey('description')) { $payload.description = $description; }
        if ($PSBoundParameters.ContainsKey('value')) { $payload.value = $value; }
        if ($PSBoundParameters.ContainsKey('category')) { $payload.category = $category; }
        # -settings wins, so a caller can reach a field this module does not
        # model yet without the named parameters fighting them for it.
        if ($PSBoundParameters.ContainsKey('settings')) {
            foreach ($key in $settings.Keys) { $payload[$key] = $settings[$key]; }
        }
        Write-Verbose "creating fog setting";
        return (Add-FogTypeName -InputObject (New-FogObject -type object -coreObject setting -jsonData ($payload | ConvertTo-Json -Compress)) -TypeName 'FogApi.Setting');
    }

}
